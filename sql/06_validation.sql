USE ROLE {{ROLE}};
USE WAREHOUSE {{WH}};
USE SCHEMA {{BUILD_DB}}.PUBLIC;

-- -----------------------------------------------------------------------------
-- 1. Integrity rules (DATA_MODEL.md "Data Integrity Rules")
-- -----------------------------------------------------------------------------
SELECT 'R1 invoices only for Approved POs' AS CHECK_NAME, COUNT(*) AS VIOLATIONS
FROM PO_INVOICES I JOIN PO_TRANSACTIONS P USING (PO_ID) WHERE P.STATUS <> 'Approved'
UNION ALL SELECT 'R1 invoice supplier = PO supplier', COUNT(*)
FROM PO_INVOICES I JOIN PO_TRANSACTIONS P USING (PO_ID) WHERE I.SUPPLIER_ID <> P.SUPPLIER_ID
UNION ALL SELECT 'R1 invoice date >= PO date', COUNT(*)
FROM PO_INVOICES I JOIN PO_TRANSACTIONS P USING (PO_ID) WHERE I.INVOICE_DATE < P.PO_DATE
UNION ALL SELECT 'R1 invoices do not exceed PO amount', COUNT(*)
FROM (SELECT P.PO_ID FROM PO_INVOICES I JOIN PO_TRANSACTIONS P USING (PO_ID)
      GROUP BY P.PO_ID, P.AMOUNT HAVING SUM(I.INVOICE_AMOUNT) > P.AMOUNT + 0.05)
UNION ALL SELECT 'R1 no non-positive invoices', COUNT(*) FROM PO_INVOICES WHERE INVOICE_AMOUNT <= 0
UNION ALL SELECT 'R2 approval level matches amount', COUNT(*)
FROM PO_TRANSACTIONS
WHERE APPROVAL_LEVEL <> CASE WHEN AMOUNT <= 5000 THEN 'Self' WHEN AMOUNT <= 50000 THEN 'Manager'
                             WHEN AMOUNT <= 250000 THEN 'Executive' ELSE 'LT Panel' END
UNION ALL SELECT 'R3 Active contracts not past end date', COUNT(*)
FROM CONTRACTS WHERE CONTRACT_STATUS IN ('Active', 'Under Renewal') AND END_DATE < '2026-10-31'::DATE
UNION ALL SELECT 'R3 Expired contracts ended before as-at', COUNT(*)
FROM CONTRACTS WHERE CONTRACT_STATUS = 'Expired' AND END_DATE >= '2026-10-31'::DATE
UNION ALL SELECT 'R3 contract start <= end', COUNT(*) FROM CONTRACTS WHERE START_DATE > END_DATE
UNION ALL SELECT 'R4 incident centre = related PO centre', COUNT(*)
FROM INCIDENT_LOG I JOIN PO_TRANSACTIONS P ON P.PO_ID = I.RELATED_PO_ID WHERE I.PROFIT_CENTRE_ID <> P.PROFIT_CENTRE_ID
UNION ALL SELECT 'R4 incident centre = related asset centre', COUNT(*)
FROM INCIDENT_LOG I JOIN ASSET_REGISTER A ON A.ASSET_ID = I.RELATED_ASSET_ID WHERE I.PROFIT_CENTRE_ID <> A.PROFIT_CENTRE_ID
UNION ALL SELECT 'R5 assessments only in serviced states', COUNT(*)
FROM SUPPLIER_ASSESSMENTS SA JOIN SUPPLIERS S USING (SUPPLIER_ID) JOIN PROFIT_CENTRES P USING (PROFIT_CENTRE_ID)
WHERE NOT ARRAY_CONTAINS(P.STATE::VARIANT, S.SERVICE_REGIONS)
UNION ALL SELECT 'R5 POs only to suppliers servicing the state', COUNT(*)
FROM PO_TRANSACTIONS T JOIN SUPPLIERS S USING (SUPPLIER_ID) JOIN PROFIT_CENTRES P USING (PROFIT_CENTRE_ID)
WHERE NOT ARRAY_CONTAINS(P.STATE::VARIANT, S.SERVICE_REGIONS)
UNION ALL SELECT 'R6 lifeguards only at pool centres', COUNT(*)
FROM STAFF_ROSTER R JOIN PROFIT_CENTRES P USING (PROFIT_CENTRE_ID) WHERE R.ROLE_TYPE = 'Pool Lifeguard' AND NOT P.HAS_POOL
UNION ALL SELECT 'R6 pool assets only at pool centres', COUNT(*)
FROM ASSET_REGISTER A JOIN PROFIT_CENTRES P USING (PROFIT_CENTRE_ID) WHERE A.ASSET_CATEGORY = 'Pool' AND NOT P.HAS_POOL
UNION ALL SELECT 'R7 no in-progress assessment periods', COUNT(*)
FROM SUPPLIER_ASSESSMENTS WHERE ASSESSMENT_PERIOD NOT IN
  ('H1-FY2023','H2-FY2023','H1-FY2024','H2-FY2024','H1-FY2025','H2-FY2025','H1-FY2026','H2-FY2026')
UNION ALL SELECT 'R7 assessment scores within 1.00-5.00', COUNT(*)
FROM SUPPLIER_ASSESSMENTS
WHERE LEAST(QUALITY_SCORE, TIMELINESS_SCORE, COMMUNICATION_SCORE, VALUE_FOR_MONEY_SCORE, OVERALL_SCORE) < 1
   OR GREATEST(QUALITY_SCORE, TIMELINESS_SCORE, COMMUNICATION_SCORE, VALUE_FOR_MONEY_SCORE, OVERALL_SCORE) > 5
UNION ALL SELECT 'FK PO -> buyer/supplier/centre/code/GL', COUNT(*)
FROM PO_TRANSACTIONS T
LEFT JOIN BUYERS B USING (BUYER_ID) LEFT JOIN SUPPLIERS S USING (SUPPLIER_ID) LEFT JOIN PROFIT_CENTRES P USING (PROFIT_CENTRE_ID)
LEFT JOIN SPEND_CODES C USING (SPEND_CODE_ID) LEFT JOIN GL_HIERARCHY G USING (GL_ACCOUNT_ID)
WHERE B.BUYER_ID IS NULL OR S.SUPPLIER_ID IS NULL OR P.PROFIT_CENTRE_ID IS NULL OR C.SPEND_CODE_ID IS NULL OR G.GL_ACCOUNT_ID IS NULL
UNION ALL SELECT 'FK email sender = buyer email', COUNT(*)
FROM PROCUREMENT_EMAILS E LEFT JOIN BUYERS B ON B.EMAIL = E.SENDER_EMAIL WHERE B.BUYER_ID IS NULL
UNION ALL SELECT 'FK email PO/invoice/supplier exist', COUNT(*)
FROM PROCUREMENT_EMAILS E
LEFT JOIN PO_TRANSACTIONS P ON P.PO_ID = E.RELATED_PO_ID
LEFT JOIN PO_INVOICES I ON I.INVOICE_ID = E.RELATED_INVOICE_ID
LEFT JOIN SUPPLIERS S ON S.SUPPLIER_ID = E.RELATED_SUPPLIER_ID
WHERE (E.RELATED_PO_ID IS NOT NULL AND P.PO_ID IS NULL) OR (E.RELATED_INVOICE_ID IS NOT NULL AND I.INVOICE_ID IS NULL) OR S.SUPPLIER_ID IS NULL
UNION ALL SELECT 'FK warranty supplier exists', COUNT(*)
FROM ASSET_REGISTER A LEFT JOIN SUPPLIERS S ON S.SUPPLIER_ID = A.WARRANTY_SUPPLIER_ID
WHERE A.WARRANTY_SUPPLIER_ID IS NOT NULL AND S.SUPPLIER_ID IS NULL
UNION ALL SELECT 'Dates within Jul 2022 - as-at', COUNT(*)
FROM (SELECT PO_DATE AS D FROM PO_TRANSACTIONS UNION ALL SELECT INVOICE_DATE FROM PO_INVOICES
      UNION ALL SELECT INCIDENT_DATE FROM INCIDENT_LOG UNION ALL SELECT EMAIL_DATE FROM PROCUREMENT_EMAILS)
WHERE D < '2022-07-01'::DATE OR D > '2026-10-31'::DATE
UNION ALL SELECT 'Staff cost rows = headcount x 2', COUNT(*)
FROM STAFF_ROSTER R
LEFT JOIN (SELECT PROFIT_CENTRE_ID, ROLE_TYPE, MONTH, COUNT(*) AS N FROM STAFF_COSTS GROUP BY 1, 2, 3) C
  ON C.PROFIT_CENTRE_ID = R.PROFIT_CENTRE_ID AND C.ROLE_TYPE = R.ROLE_TYPE AND C.MONTH = R.MONTH
WHERE COALESCE(C.N, 0) <> R.HEADCOUNT * 2
UNION ALL SELECT 'Budget grid complete (2,300 lines)', ABS(COUNT(*) - 2300) FROM BUDGETS;

-- -----------------------------------------------------------------------------
-- 2. Q2 golden answer (as at 2026-10-31). Expect exactly 4 suppliers:
--    SUP014, SUP015, SUP026, SUP040
-- -----------------------------------------------------------------------------
WITH PERIOD_ORDER AS (
  SELECT ASSESSMENT_PERIOD,
         TO_NUMBER(SUBSTR(ASSESSMENT_PERIOD, 6, 4)) * 10 + TO_NUMBER(SUBSTR(ASSESSMENT_PERIOD, 2, 1)) AS ORD
  FROM (SELECT DISTINCT ASSESSMENT_PERIOD FROM SUPPLIER_ASSESSMENTS)
), LAST2 AS (
  SELECT ASSESSMENT_PERIOD FROM PERIOD_ORDER QUALIFY ROW_NUMBER() OVER (ORDER BY ORD DESC) <= 2
), SCORES AS (
  SELECT SA.SUPPLIER_ID, SA.ASSESSMENT_PERIOD, AVG(SA.OVERALL_SCORE) AS SUPPLIER_SCORE
  FROM SUPPLIER_ASSESSMENTS SA JOIN LAST2 USING (ASSESSMENT_PERIOD)
  GROUP BY 1, 2
), RULE_A AS (
  SELECT SUPPLIER_ID FROM SCORES GROUP BY 1 HAVING COUNT(*) = 2 AND MAX(SUPPLIER_SCORE) < 3.00
), RULE_B AS (
  SELECT P.SUPPLIER_ID
  FROM INCIDENT_LOG I JOIN PO_TRANSACTIONS P ON P.PO_ID = I.RELATED_PO_ID
  WHERE I.SEVERITY IN ('High', 'Critical')
    AND I.INCIDENT_DATE > DATEADD(MONTH, -6, '2026-10-31'::DATE) AND I.INCIDENT_DATE <= '2026-10-31'::DATE
  GROUP BY 1 HAVING COUNT(*) >= 3
), AT_RISK AS (
  SELECT SUPPLIER_ID, 'Scores below 3.00 in H1-FY2026 and H2-FY2026' AS REASON FROM RULE_A
  UNION ALL
  SELECT SUPPLIER_ID, '3+ High/Critical incidents in last 6 months' FROM RULE_B
), EXPIRING AS (
  SELECT SUPPLIER_ID, MIN(END_DATE) AS NEXT_EXPIRY, COUNT(*) AS N_CONTRACTS
  FROM CONTRACTS
  WHERE CONTRACT_STATUS = 'Active' AND RENEWAL_TYPE <> 'Auto-renew'
    AND END_DATE BETWEEN '2026-10-31'::DATE AND DATEADD(DAY, 90, '2026-10-31'::DATE)
  GROUP BY 1
), SPEND AS (
  SELECT SUPPLIER_ID, SUM(AMOUNT) AS FY2026_SPEND
  FROM PO_TRANSACTIONS WHERE STATUS = 'Approved' AND FINANCIAL_YEAR = 'FY2026'
  GROUP BY 1
)
SELECT S.SUPPLIER_ID, S.SUPPLIER_NAME, S.CATEGORY, LISTAGG(AR.REASON, '; ') AS AT_RISK_REASON,
       E.NEXT_EXPIRY, E.N_CONTRACTS, ROUND(MAX(SP.FY2026_SPEND), 2) AS FY2026_APPROVED_SPEND
FROM AT_RISK AR
JOIN EXPIRING E USING (SUPPLIER_ID)
JOIN SUPPLIERS S USING (SUPPLIER_ID)
LEFT JOIN SPEND SP USING (SUPPLIER_ID)
GROUP BY 1, 2, 3, 5, 6
ORDER BY FY2026_APPROVED_SPEND DESC;

-- -----------------------------------------------------------------------------
-- 3. Trap matrix: one row per supplier of interest. CORRECT must be TRUE only
--    for the 4 golden suppliers; each decoy flips exactly one naive reading.
-- -----------------------------------------------------------------------------
WITH PS AS (
  SELECT SUPPLIER_ID, ASSESSMENT_PERIOD, AVG(OVERALL_SCORE) AS S
  FROM SUPPLIER_ASSESSMENTS GROUP BY 1, 2
), A_CORRECT AS (      -- H1-FY2026 and H2-FY2026, supplier average
  SELECT SUPPLIER_ID FROM PS WHERE ASSESSMENT_PERIOD IN ('H1-FY2026', 'H2-FY2026')
  GROUP BY 1 HAVING COUNT(*) = 2 AND MAX(S) < 3.00
), A_LEXICAL AS (      -- alphabetical sort: H2-FY2026 and H2-FY2025
  SELECT SUPPLIER_ID FROM PS WHERE ASSESSMENT_PERIOD IN ('H2-FY2026', 'H2-FY2025')
  GROUP BY 1 HAVING COUNT(*) = 2 AND MAX(S) < 3.00
), A_LATEST_ONLY AS (  -- only the latest period
  SELECT SUPPLIER_ID FROM PS WHERE ASSESSMENT_PERIOD = 'H2-FY2026' AND S < 3.00
), A_NOT_REC AS (      -- guess from the recommendation column
  SELECT DISTINCT SUPPLIER_ID FROM SUPPLIER_ASSESSMENTS
  WHERE ASSESSMENT_PERIOD = 'H2-FY2026' AND RECOMMENDATION = 'Not Recommended'
  QUALIFY COUNT(*) OVER (PARTITION BY SUPPLIER_ID) >= 5
), B_PO AS (
  SELECT P.SUPPLIER_ID FROM INCIDENT_LOG I JOIN PO_TRANSACTIONS P ON P.PO_ID = I.RELATED_PO_ID
  WHERE I.SEVERITY IN ('High', 'Critical') AND I.INCIDENT_DATE > '2026-04-30'::DATE
  GROUP BY 1 HAVING COUNT(*) >= 3
), B_ANY AS (          -- also counting warranty-linked incidents
  SELECT SUPPLIER_ID FROM (
    SELECT P.SUPPLIER_ID, I.INCIDENT_ID FROM INCIDENT_LOG I JOIN PO_TRANSACTIONS P ON P.PO_ID = I.RELATED_PO_ID
    WHERE I.SEVERITY IN ('High', 'Critical') AND I.INCIDENT_DATE > '2026-04-30'::DATE
    UNION
    SELECT A.WARRANTY_SUPPLIER_ID, I.INCIDENT_ID FROM INCIDENT_LOG I JOIN ASSET_REGISTER A ON A.ASSET_ID = I.RELATED_ASSET_ID
    WHERE I.SEVERITY IN ('High', 'Critical') AND I.INCIDENT_DATE > '2026-04-30'::DATE AND A.WARRANTY_SUPPLIER_ID IS NOT NULL)
  GROUP BY 1 HAVING COUNT(*) >= 3
), C_CORRECT AS (
  SELECT DISTINCT SUPPLIER_ID FROM CONTRACTS
  WHERE CONTRACT_STATUS = 'Active' AND RENEWAL_TYPE <> 'Auto-renew' AND END_DATE BETWEEN '2026-10-31' AND '2027-01-29'
), C_ANY_RENEWAL AS (  -- ignoring the Auto-renew exclusion
  SELECT DISTINCT SUPPLIER_ID FROM CONTRACTS
  WHERE CONTRACT_STATUS = 'Active' AND END_DATE BETWEEN '2026-10-31' AND '2027-01-29'
), C_ANY_STATUS AS (   -- counting Under Renewal as active
  SELECT DISTINCT SUPPLIER_ID FROM CONTRACTS
  WHERE CONTRACT_STATUS IN ('Active', 'Under Renewal') AND RENEWAL_TYPE <> 'Auto-renew' AND END_DATE BETWEEN '2026-10-31' AND '2027-01-29'
), C_120D AS (         -- a wider window
  SELECT DISTINCT SUPPLIER_ID FROM CONTRACTS
  WHERE CONTRACT_STATUS = 'Active' AND RENEWAL_TYPE <> 'Auto-renew' AND END_DATE BETWEEN '2026-10-31' AND '2027-02-28'
)
SELECT S.SUPPLIER_ID,
       (S.SUPPLIER_ID IN (SELECT * FROM A_CORRECT) OR S.SUPPLIER_ID IN (SELECT * FROM B_PO))
         AND S.SUPPLIER_ID IN (SELECT * FROM C_CORRECT)                   AS CORRECT,
       S.SUPPLIER_ID IN (SELECT * FROM A_CORRECT)                         AS A_SCORES,
       S.SUPPLIER_ID IN (SELECT * FROM A_LEXICAL)                         AS A_LEXICAL_SORT,
       S.SUPPLIER_ID IN (SELECT * FROM A_LATEST_ONLY)                     AS A_LATEST_ONLY,
       S.SUPPLIER_ID IN (SELECT * FROM A_NOT_REC)                         AS A_NOT_RECOMMENDED,
       S.SUPPLIER_ID IN (SELECT * FROM B_PO)                              AS B_INCIDENTS_PO,
       S.SUPPLIER_ID IN (SELECT * FROM B_ANY)                             AS B_INCL_WARRANTY,
       S.SUPPLIER_ID IN (SELECT * FROM C_CORRECT)                         AS C_EXPIRING,
       S.SUPPLIER_ID IN (SELECT * FROM C_ANY_RENEWAL)                     AS C_INCL_AUTORENEW,
       S.SUPPLIER_ID IN (SELECT * FROM C_ANY_STATUS)                      AS C_INCL_UNDER_RENEWAL,
       S.SUPPLIER_ID IN (SELECT * FROM C_120D)                            AS C_120_DAYS
FROM SUPPLIERS S
WHERE S.SUPPLIER_ID IN (SELECT * FROM A_CORRECT UNION SELECT * FROM A_LEXICAL UNION SELECT * FROM A_LATEST_ONLY
                        UNION SELECT * FROM A_NOT_REC UNION SELECT * FROM B_PO UNION SELECT * FROM B_ANY)
ORDER BY CORRECT DESC, S.SUPPLIER_ID;
